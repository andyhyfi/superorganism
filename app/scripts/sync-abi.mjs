// Copies the contract ABIs from the Foundry build into src/abi.ts, and the local chain
// addresses into src/local.json. Run after ./local.sh has deployed.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const contracts = join(here, '..', '..', 'contracts')

const abi = name => JSON.parse(readFileSync(join(contracts, 'out', `${name}.sol`, `${name}.json`), 'utf8')).abi
// The local chain runs EvolutionDemo: Evolution plus the test dials. Its ABI is a superset.
const out = `// Generated by scripts/sync-abi.mjs from the Foundry build. Do not edit.
export const evolutionAbi = ${JSON.stringify(abi('EvolutionDemo'), null, 2)} as const

export const usdcAbi = ${JSON.stringify(abi('MockUSDC'), null, 2)} as const
`
writeFileSync(join(here, '..', 'src', 'abi.ts'), out)
writeFileSync(
  join(here, 'abi-node.mjs'),
  `// Generated by scripts/sync-abi.mjs. Do not edit.\nexport const evolutionAbi = ${JSON.stringify(abi('EvolutionDemo'))}\nexport const usdcAbi = ${JSON.stringify(abi('MockUSDC'))}\n`,
)

const deployments = join(contracts, 'deployments', 'local.json')
if (existsSync(deployments)) {
  writeFileSync(join(here, '..', 'src', 'local.json'), readFileSync(deployments))
  console.log('abi.ts and local.json written')
} else {
  console.log('abi.ts written; no local deployment yet (run ./local.sh)')
}
